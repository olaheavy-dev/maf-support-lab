using System.Globalization;
using System.Text;
using System.Text.Json.Nodes;

namespace Support.Evaluations;

/// <summary>
/// The baseline and cross-backend comparison: reads the run documents both backends produced and writes one
/// Markdown summary, with each run's identity (so it can be reproduced), each case's status on each backend, and
/// latency. Statuses come from contract facts, so the backends compare without identical wording.
/// </summary>
internal static class Comparison
{
    public static async Task<int> WriteAsync(string[] args)
    {
        string? results = null, output = null;
        for (var i = 0; i < args.Length; i++)
        {
            switch (args[i])
            {
                case "--results" when i + 1 < args.Length: results = args[++i]; break;
                case "--out" when i + 1 < args.Length: output = args[++i]; break;
                default: throw new ArgumentException($"Unknown or incomplete option {args[i]}.");
            }
        }

        if (results is null || output is null)
        {
            throw new ArgumentException("compare needs --results DIR and --out FILE.");
        }

        List<JsonObject> runs = [];
        foreach (var file in Directory.GetFiles(results, "*.json").Order(StringComparer.Ordinal))
        {
            var run = JsonNode.Parse(await File.ReadAllTextAsync(file).ConfigureAwait(false))!.AsObject();
            if (!run.ContainsKey("results"))
            {
                continue; // another result kind in the same folder (quality, load, the report's JSON): not a run document
            }

            var problems = EvaluationSchemas.Errors(EvaluationSchemas.Run, run);
            if (problems.Count > 0)
            {
                throw new InvalidDataException($"{Path.GetFileName(file)} is not a valid run document: {problems[0]}");
            }

            runs.Add(run);
        }

        // The baseline compares behaviour runs across backends. Native evaluation runs score recordings of one
        // agent, not a backend's API, so they are left out rather than mixed into the side-by-side table.
        runs = [.. runs.Where(IsBehaviourRun)];
        var markdown = Render(runs);
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
        await File.WriteAllTextAsync(output, markdown).ConfigureAwait(false);
        Console.WriteLine($"Wrote {output} from {runs.Count} run documents.");
        return 0;
    }

    internal static bool IsBehaviourRun(JsonObject run) =>
        run["run"]!["configuration"]?["mode"]?.GetValue<string>() is "launch" or "endpoint";

    internal static string Render(IReadOnlyList<JsonObject> runs)
    {
        static string S(JsonNode? node) => node?.GetValue<string>() ?? "";
        var backends = runs.Select(r => S(r["run"]!["backend"])).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToList();
        var datasets = runs.Select(r => S(r["run"]!["dataset"]!["dataset_id"])).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToList();
        JsonObject? RunFor(string backend, string dataset) =>
            runs.FirstOrDefault(r => S(r["run"]!["backend"]) == backend && S(r["run"]!["dataset"]!["dataset_id"]) == dataset);

        var text = new StringBuilder();
        text.AppendLine("# Deterministic behaviour baseline");
        text.AppendLine();
        text.AppendLine("Generated by `Support.Evaluations compare` from the run documents (evaluations/results). Fake model mode: these are contract facts (routes, outcomes, reply kinds, operation states, tools), not answer quality, which the model-judged quality lane scores separately.");
        text.AppendLine();
        text.AppendLine("## Runs");
        text.AppendLine();
        text.AppendLine("| Backend | Dataset | Version | Run id | Commit | Model | Mode | Runner | Scorer | Passed | Failed | Error | Skipped |");
        text.AppendLine("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
        foreach (var run in runs.OrderBy(r => S(r["run"]!["backend"]), StringComparer.Ordinal).ThenBy(r => S(r["run"]!["dataset"]!["dataset_id"]), StringComparer.Ordinal))
        {
            var meta = run["run"]!;
            var summary = run["summary"]!;
            var commit = S(meta["source_commit"]);
            text.AppendLine(CultureInfo.InvariantCulture, $"| {S(meta["backend"])} | {S(meta["dataset"]!["dataset_id"])} | {S(meta["dataset"]!["dataset_version"])} | `{S(meta["run_id"])}` | `{(commit.Length > 12 ? commit[..12] : commit)}` | {S(meta["model"]!["mode"])} | {S(meta["configuration"]!["mode"])} | {S(meta["runner"]!["version"])} | {S(meta["scorer"]!["name"])} {S(meta["scorer"]!["version"])} | {summary["passed"]} | {summary["failed"]} | {summary["error"]} | {summary["skipped"]} |");
        }

        text.AppendLine();
        text.AppendLine("## Cases, side by side");
        text.AppendLine();
        text.AppendLine(CultureInfo.InvariantCulture, $"| Dataset | Case | Split | {string.Join(" | ", backends.Select(b => $"{b} status | {b} ms"))} | Same status |");
        text.AppendLine(CultureInfo.InvariantCulture, $"| --- | --- | --- | {string.Join(" | ", backends.Select(_ => "--- | ---:"))} | --- |");
        var same = 0;
        var total = 0;
        foreach (var dataset in datasets)
        {
            var caseIds = backends.SelectMany(b => RunFor(b, dataset)?["results"]!.AsArray().Select(r => S(r!["case_id"])) ?? []).Distinct(StringComparer.Ordinal);
            foreach (var caseId in caseIds)
            {
                var cells = backends.Select(b => RunFor(b, dataset)?["results"]!.AsArray().FirstOrDefault(r => S(r!["case_id"]) == caseId)).ToList();
                var statuses = cells.Select(c => c is null ? "missing" : S(c["status"])).ToList();
                var split = cells.Select(c => S(c?["split"])).FirstOrDefault(s => s.Length > 0) ?? "";
                var agree = statuses.Distinct(StringComparer.Ordinal).Count() == 1;
                same += agree ? 1 : 0;
                total++;
                var columns = cells.Select((c, i) => $"{statuses[i]} | {(c is null || S(c["status"]) == "skipped" ? "" : c["latency_ms"]!.GetValue<double>().ToString("0", CultureInfo.InvariantCulture))}");
                text.AppendLine(CultureInfo.InvariantCulture, $"| {dataset} | {caseId} | {split} | {string.Join(" | ", columns)} | {(agree ? "yes" : "**no**")} |");
            }
        }

        text.AppendLine();
        text.AppendLine("## Summary");
        text.AppendLine();
        text.AppendLine(CultureInfo.InvariantCulture, $"- **Agreement:** {same} of {total} cases have the same status on {string.Join(" and ", backends)}.");
        foreach (var backend in backends)
        {
            var latencies = runs.Where(r => S(r["run"]!["backend"]) == backend)
                .SelectMany(r => r["results"]!.AsArray())
                .Where(r => S(r!["status"]) == "passed")
                .Select(r => r!["latency_ms"]!.GetValue<double>())
                .Order()
                .ToList();
            var counts = runs.Where(r => S(r["run"]!["backend"]) == backend).Select(r => r["summary"]!).ToList();
            int Sum(string key) => counts.Sum(c => c[key]!.GetValue<int>());
            var median = latencies.Count == 0 ? 0 : latencies[latencies.Count / 2];
            var p90 = latencies.Count == 0 ? 0 : latencies[Math.Min(latencies.Count - 1, (int)Math.Ceiling(latencies.Count * 0.9) - 1)];
            text.AppendLine(CultureInfo.InvariantCulture, $"- **{backend}:** {Sum("passed")} passed, {Sum("failed")} failed, {Sum("error")} error, {Sum("skipped")} skipped; case latency over passed cases: median {median:0} ms, p90 {p90:0} ms (fake model; API time only: process startup and restarts excluded).");
        }

        text.AppendLine("- **Usage:** unknown on every case (the contract exposes no token counts), recorded as unavailable rather than zero.");
        return text.ToString();
    }
}
